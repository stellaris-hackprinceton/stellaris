#!/usr/bin/env python3
"""Docker integration checks for sources, experiments, uploads/artifacts, and SSE events.

Run from the host (stdlib only) after rebuilding and `docker compose up -d` in backend/:

    python3 scripts/integration_test.py
    python3 scripts/integration_test.py --skip-heartbeat   # skips the ~16 s idle wait

Fixtures are tiny generated files (a gradient PNG, a 1 s ffmpeg `testsrc` clip, a CSV).
All of them are uploaded with origin "simulated" and SIMULATED filenames: none of them is
an observed measurement. Creates real projects and containers, which are retained.
Does not read any .env file.
"""

