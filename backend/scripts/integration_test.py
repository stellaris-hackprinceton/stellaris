def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--skip-heartbeat", action="store_true")
    args = parser.parse_args()
    run = uuid.uuid4().hex[:8]

    print("1. Capabilities and projects")
    status, _, caps = api("GET", "/capabilities")
    check(status == 200 and {"video/mp4", "image/png", "text/csv"} <= set(caps["uploads"]["accepted_mime_types"])
          and caps["uploads"]["max_file_bytes"] > 0 and caps["event_retention_seconds"] > 0,
          "capabilities advertise implemented upload types, limits, and event retention")
    check(not any(caps["features"].values()), "capabilities still report unimplemented features as false")
    max_file = caps["uploads"]["max_file_bytes"]
    status, _, a = api("POST", "/projects", {"name": f"IT A {run}"}, {"Idempotency-Key": key()})
    status_b, _, b = api("POST", "/projects", {"name": f"IT B {run}"}, {"Idempotency-Key": key()})
    check(status == 201 and status_b == 201, "created projects A and B")
    A, B = a["id"], b["id"]

    print("2. Event stream setup")
    _, _, ws = api("GET", f"/projects/{A}/workspace")
    cursor0 = ws["event_cursor"]
    check(ws["counts"] == {"sources": 0, "experiments": 0, "runs": 0, "artifacts": 0}, "new workspace counts are zero")
    s1 = open_stream(f"/projects/{A}/events?after={cursor0}")
    check(s1.status == 200 and s1.resp_headers.get_content_type() == "text/event-stream",
          "GET /events opens text/event-stream")
    check(s1.resp_headers.get("X-Accel-Buffering") == "no" and "no-transform" in s1.resp_headers.get("Cache-Control", ""),
          "SSE response disables proxy buffering and transforms")
    status, _, err = api("GET", f"/projects/{A}/events?after=evt_garbage")
    check(status == 400 and code(err) == "INVALID_EVENT_CURSOR", "malformed cursor returns 400 INVALID_EVENT_CURSOR")
    _, _, ws_b = api("GET", f"/projects/{B}/workspace")
    status, _, err = api("GET", f"/projects/{A}/events?after={ws_b['event_cursor']}")
    check(status == 400 and code(err) == "INVALID_EVENT_CURSOR", "cursor issued for project B is rejected on project A")

    print("3. Manual sources")
    src_body = {"title": "Coefficient of restitution of bouncing balls", "url": "https://example.org/cor",
                "published_at": "2024-06"}
    k = key()
    status, h, src = api("POST", f"/projects/{A}/sources", src_body, {"Idempotency-Key": k})
    check(status == 201 and src["provider"] == "manual" and src["retrieval_status"] == "metadata_only"
          and src["authors"] == [] and src["doi"] is None and src["document_artifact_id"] is None,
          "POST /sources creates a manual metadata-only source with defaults")
    status, h, again = api("POST", f"/projects/{A}/sources", src_body, {"Idempotency-Key": k})
    check(status == 201 and again == src and h.get("Idempotent-Replayed") == "true", "source POST replays idempotently")
    for bad, label in (({**src_body, "colour": 1}, "unknown field"), ({**src_body, "url": "ftp://x"}, "non-http url"),
                       ({**src_body, "published_at": "2024-13"}, "bad published_at"), ({"url": "https://x.org"}, "missing title")):
        status, _, err = api("POST", f"/projects/{A}/sources", bad, {"Idempotency-Key": key()})
        check(status == 422 and code(err) == "VALIDATION_FAILED", f"source with {label} returns 422")
    status, _, page = api("GET", f"/projects/{A}/sources?provider=manual")
    check(status == 200 and [s["id"] for s in page["items"]] == [src["id"]], "sources list filters by provider")
    status, _, err = api("GET", f"/projects/{B}/sources/{src['id']}")
    check(status == 404, "project A's source is not visible under project B")
    status, _, claims = api("GET", f"/projects/{A}/claims")
    check(status == 200 and claims["items"] == [], "claims list is available (no public claim writes)")

    print("4. Upload validation")
    png = make_png(32, 24)
    for body, expect, label in (
        ({"filename": "x.html", "mime_type": "text/html", "size_bytes": 5, "kind": "document", "origin": "simulated"},
         (415, "UNSUPPORTED_MEDIA_TYPE"), "unsupported MIME type"),
        ({"filename": "../x.png", "mime_type": "image/png", "size_bytes": 5, "kind": "image", "origin": "simulated"},
         (422, "VALIDATION_FAILED"), "path-like filename"),
        ({"filename": "x.png", "mime_type": "image/png", "size_bytes": 5, "kind": "video", "origin": "simulated"},
         (422, "VALIDATION_FAILED"), "kind incompatible with MIME"),
        ({"filename": "x.png", "mime_type": "image/png", "size_bytes": max_file + 1, "kind": "image", "origin": "simulated"},
         (413, "UPLOAD_TOO_LARGE"), "declared size above max_file_bytes"),
        ({"filename": "x.png", "mime_type": "image/png", "size_bytes": 5, "kind": "image", "origin": "simulated", "x": 1},
         (422, "VALIDATION_FAILED"), "unknown field"),
        ({"filename": "x.mp4", "mime_type": "video/mp4", "size_bytes": 5, "kind": "video", "origin": "observed",
          "capture": {"method": "browser_camera", "recorded_at": None, "recording_permission_confirmed": False}},
         (422, "VALIDATION_FAILED"), "browser recording without permission confirmation"),
        ({"filename": "x.png", "mime_type": "image/png", "size_bytes": 5, "kind": "image", "origin": "simulated",
          "experiment_id": "exp_missing"}, (422, "INVALID_REFERENCE"), "unknown experiment_id"),
    ):
        status, _, err = api("POST", f"/projects/{A}/uploads", body, {"Idempotency-Key": key()})
        check((status, code(err)) == expect, f"upload create rejects {label} with {expect[0]} {expect[1]}")

    print("5. PNG upload lifecycle")
    status, _, up = create_upload(A, png, "SIMULATED-gradient.png", "image/png", "image")
    check(status == 201 and up["status"] == "pending" and up["artifact_id"] is None and up["expires_at"],
          "upload created as pending with expiry")
    status, _, err = complete(A, up["id"])
    check(status == 409 and code(err) == "ARTIFACT_NOT_READY", "completing before transfer returns 409 ARTIFACT_NOT_READY")
    status, err = put(A, up["id"], png, "image/jpeg")
    check(status == 415, "PUT with mismatched Content-Type returns 415")
    status, err = put(A, up["id"], png[:-3], "image/png")
    check(status == 422 and code(err) == "VALIDATION_FAILED", "short transfer returns 422 and is not marked uploaded")
    check(api("GET", f"/projects/{A}/uploads/{up['id']}")[2]["status"] == "pending", "upload stays pending after a bad transfer")
    status, _ = put(A, up["id"], png, "image/png")
    check(status == 204 and api("GET", f"/projects/{A}/uploads/{up['id']}")[2]["status"] == "uploaded",
          "PUT with the declared bytes returns 204 and marks uploaded")
    status, _ = put(A, up["id"], png, "image/png", chunked=True)
    check(status == 204, "repeating the identical transfer (chunked encoding) returns 204")
    changed = bytearray(png)
    changed[-20] ^= 0xFF
    status, err = put(A, up["id"], bytes(changed), "image/png")
    check(status == 409 and code(err) == "UPLOAD_CONTENT_CONFLICT", "different bytes after transfer return 409")
    status, _, err = api("POST", f"/projects/{A}/uploads/{up['id']}/complete", {})
    check(status == 428, "complete without Idempotency-Key returns 428")
    k = key()
    status, _, png_art = complete(A, up["id"], k)
    check(status == 200 and png_art["kind"] == "image" and png_art["origin"] == "simulated"
          and png_art["sha256"] == hashlib.sha256(png).hexdigest() and png_art["size_bytes"] == len(png)
          and png_art["metadata"].get("width_px") == 32 and png_art["metadata"].get("height_px") == 24
          and "uploaded_at" in png_art["metadata"], "complete returns an artifact with server-computed hash and dimensions")
    status, h, again = complete(A, up["id"], k)
    check(status == 200 and again == png_art and h.get("Idempotent-Replayed") == "true", "complete replays with the same key")
    status, _, again = complete(A, up["id"])
    check(status == 200 and again == png_art, "complete with a new key returns the same artifact")
    status, _, got = api("GET", f"/projects/{A}/uploads/{up['id']}")
    check(got["status"] == "completed" and got["artifact_id"] == png_art["id"], "upload shows completed with artifact_id")

    print("6. Rejected content")
    status, _, up2 = create_upload(A, png, "SIMULATED-wrong.png", "image/png", "image",
                                   extra={"sha256": hashlib.sha256(b"other").hexdigest()}, sha=False)
    status, err = put(A, up2["id"], png, "image/png")
    check(status == 422 and code(err) == "HASH_MISMATCH", "declared sha256 mismatch returns 422 HASH_MISMATCH")
    status, _, up3 = create_upload(A, b"0123456789", "SIMULATED-small.csv", "text/csv", "dataset")
    status, err = put(A, up3["id"], b"0123456789ABCDEFGHIJ", "text/csv")
    check(status == 413 and code(err) == "UPLOAD_TOO_LARGE", "sending more bytes than declared returns 413")
    status, _, up4 = create_upload(A, png, "SIMULATED-not-a-video.mp4", "video/mp4", "video")
    put(A, up4["id"], png, "video/mp4")
    status, _, err = complete(A, up4["id"])
    check(status == 422 and code(err) == "MEDIA_DECODE_FAILED", "PNG bytes declared as video/mp4 fail with MEDIA_DECODE_FAILED")
    status, _, got = api("GET", f"/projects/{A}/uploads/{up4['id']}")
    check(got["status"] == "failed" and got["error"]["code"] == "MEDIA_DECODE_FAILED", "failed upload records its error")
    status, _, err = complete(A, up4["id"])
    check(status == 422 and code(err) == "MEDIA_DECODE_FAILED", "completing a failed upload returns the same error")
    status, err = put(A, up4["id"], png, "video/mp4")
    check(status == 409 and code(err) == "UPLOAD_FAILED", "PUT to a failed upload returns 409")
    bad_text = b"t_s,height\n0,\xff\xfe\n"
    status, _, up5 = create_upload(A, bad_text, "SIMULATED-bad.csv", "text/csv", "dataset")
    put(A, up5["id"], bad_text, "text/csv")
    status, _, err = complete(A, up5["id"])
    check(status == 422 and code(err) == "MEDIA_DECODE_FAILED", "invalid UTF-8 CSV fails validation")

    print("7. Video upload, downloads, and ranges")
    video = make_video()
    _, vid = upload_artifact(A, video, "SIMULATED-testsrc.mp4", "video/mp4", "video", chunked=True)
    meta = vid["metadata"]
    check(meta.get("width_px") == 64 and meta.get("height_px") == 48 and 900 <= meta.get("duration_ms", 0) <= 1100
          and meta.get("nominal_frame_rate_fps") == 10, f"video metadata comes from ffprobe ({meta})")
    csv = b"# SIMULATED data generated by integration_test.py, not observed\nt_s,height_px\n0.0,100\n0.1,80\n"
    _, csv_art = upload_artifact(A, csv, "SIMULATED-heights.csv", "text/csv", "dataset")
    path = f"/projects/{A}/artifacts/{vid['id']}/content"
    status, h, data = raw("GET", path)
    check(status == 200 and data == video and h.get("ETag") == f'"{vid["sha256"]}"'
          and h.get("Content-Type") == "video/mp4" and h.get("Accept-Ranges") == "bytes",
          "full download returns the exact bytes, stored type, and sha256 ETag")
    check(h.get("Content-Disposition", "").startswith("attachment;") and h.get("X-Content-Type-Options") == "nosniff",
          "download defaults to attachment with nosniff")
    status, h, data = raw("GET", path, headers={"Range": "bytes=0-99"})
    check(status == 206 and data == video[:100] and h.get("Content-Range") == f"bytes 0-99/{len(video)}", "Range 0-99 returns 206")
    status, h, data = raw("GET", path, headers={"Range": "bytes=-10"})
    check(status == 206 and data == video[-10:], "suffix range returns the final bytes")
    status, h, data = raw("GET", path, headers={"Range": f"bytes={len(video)}-"})
    check(status == 416 and h.get("Content-Range") == f"bytes */{len(video)}", "unsatisfiable range returns 416")
    status, h, data = raw("GET", path, headers={"Range": "bytes=0-9", "If-Range": '"stale"'})
    check(status == 200 and data == video, "mismatched If-Range serves the full representation")
    status, h, _ = raw("GET", path + "?disposition=inline")
    check(status == 200 and h.get("Content-Disposition", "").startswith("inline;"), "inline allowed for video")
    status, h, data = raw("GET", f"/projects/{A}/artifacts/{csv_art['id']}/content?disposition=inline")
    check(status == 200 and data == csv and h.get("Content-Type", "").startswith("text/csv"), "inline allowed for plain text")

    print("8. Project-volume storage and isolation")
    ctr_a, ctr_b = container_for(A), container_for(B)
    stored = f"/workspace/data/artifacts/{vid['id']}"
    out = docker("exec", ctr_a, "sha256sum", stored).stdout.decode().split()[0]
    check(out == vid["sha256"], "artifact bytes are in project A's volume with the recorded hash")
    out = docker("exec", ctr_a, "stat", "-c", "%u:%g:%a", stored).stdout.decode().strip()
    check(out == "0:0:444", "stored artifact is root-owned and read-only (0444)")
    rc = docker("exec", ctr_a, "python", "-c", "import sys; open(sys.argv[1], 'ab')", stored, check_rc=False).returncode
    check(rc != 0, "project runtime user cannot modify the stored artifact")
    rc = docker("exec", ctr_b, "test", "!", "-e", stored, check_rc=False).returncode
    check(rc == 0, "artifact is absent from project B's volume")
    status, _, _ = api("GET", f"/projects/{B}/artifacts/{vid['id']}")
    status2, _, _ = raw("GET", f"/projects/{B}/artifacts/{vid['id']}/content")
    check(status == 404 and status2 == 404, "project A's artifact is 404 under project B")
    _, b_art = upload_artifact(B, csv, "SIMULATED-b.csv", "text/csv", "dataset")

    print("9. Experiments, references, and ETags")
    exp_body = {
        "title": "Bounce height decay (SIMULATED fixture check)", "hypothesis": "Each bounce retains a constant height ratio.",
        "method": "physical", "protocol_markdown": "Drop the ball and record it.",
        "variables": [{"name": "bounce height", "role": "dependent", "description": "Apex height", "unit": "px"}],
        "success_criteria": ["At least three bounces detected"],
        "input_artifact_ids": [vid["id"], png_art["id"]],
        "calibration": {"mode": "reference_length", "artifact_id": vid["id"], "frame_index": 0,
                        "point_a_px": [1, 1], "point_b_px": [50.5, 40], "reference_length_m": 1.0,
                        "reference_uncertainty_m": None, "assumptions": ["Reference lies in the ball's plane"]},
        "limitations": ["Fixture is simulated"],
    }
    k = key()
    status, h, exp = api("POST", f"/projects/{A}/experiments", exp_body, {"Idempotency-Key": k})
    check(status == 201 and exp["revision"] == 1 and h.get("ETag") == '"1"' and h.get("Location", "").endswith(exp["id"]),
          "POST /experiments creates revision 1 with ETag and Location")
    status, h, again = api("POST", f"/projects/{A}/experiments", exp_body, {"Idempotency-Key": k})
    check(status == 201 and again == exp and h.get("Idempotent-Replayed") == "true", "experiment POST replays idempotently")
    cases = (
        ({**exp_body, "input_artifact_ids": [b_art["id"]], "calibration": {"mode": "none", "assumptions": []}},
         "INVALID_REFERENCE", "another project's artifact"),
        ({**exp_body, "input_artifact_ids": [up2["id"]], "calibration": {"mode": "none", "assumptions": []}},
         "INVALID_REFERENCE", "an uncompleted upload ID"),
        ({**exp_body, "calibration": {**exp_body["calibration"], "point_b_px": [64, 10]}}, "VALIDATION_FAILED",
         "a calibration point outside the frame"),
        ({**exp_body, "calibration": {**exp_body["calibration"], "point_b_px": [1, 1]}}, "VALIDATION_FAILED",
         "identical calibration points"),
        ({**exp_body, "calibration": {**exp_body["calibration"], "artifact_id": png_art["id"], "frame_index": 2}},
         "VALIDATION_FAILED", "a nonzero frame_index on an image"),
        ({**exp_body, "input_artifact_ids": [png_art["id"]]}, "VALIDATION_FAILED", "calibration on a non-input artifact"),
        ({k2: v for k2, v in exp_body.items() if k2 != "limitations"}, "VALIDATION_FAILED", "a missing field"),
        ({**exp_body, "status": "done"}, "VALIDATION_FAILED", "an unknown field"),
    )
    for body, expect, label in cases:
        status, _, err = api("POST", f"/projects/{A}/experiments", body, {"Idempotency-Key": key()})
        check(status == 422 and code(err) == expect, f"experiment with {label} returns 422 {expect}")
    for token in ("NaN", "Infinity", "1e999"):
        text = json.dumps(exp_body).replace('"reference_length_m": 1.0', f'"reference_length_m": {token}')
        status, _, body = raw("POST", f"/projects/{A}/experiments", text.encode(),
                              {"Content-Type": "application/json", "Idempotency-Key": key()})
        check(status == 400 and code(json.loads(body)) == "MALFORMED_JSON", f"non-finite number {token} returns 400")
    epath = f"/projects/{A}/experiments/{exp['id']}"
    status, h, got = api("GET", epath)
    check(status == 200 and h.get("ETag") == '"1"' and got == exp, "GET experiment returns ETag")
    status, _, err = api("PATCH", epath, {"title": "Renamed"})
    check(status == 428, "experiment PATCH without If-Match returns 428")
    status, h, exp2 = api("PATCH", epath, {"title": "Renamed"}, {"If-Match": '"1"'})
    check(status == 200 and exp2["revision"] == 2 and h.get("ETag") == '"2"', "experiment PATCH bumps revision")
    status, _, err = api("PATCH", epath, {"title": "Stale"}, {"If-Match": '"1"'})
    check(status == 412 and code(err) == "REVISION_CONFLICT", "stale experiment ETag returns 412")
    status, h, same = api("PATCH", epath, {"title": "Renamed"}, {"If-Match": '"2"'})
    check(status == 200 and same["revision"] == 2, "no-op experiment PATCH keeps the revision")
    status, _, err = api("PATCH", epath, {"input_artifact_ids": [b_art["id"]]}, {"If-Match": '"2"'})
    check(status == 422 and code(err) == "INVALID_REFERENCE", "PATCH with another project's artifact returns 422")

    print("10. Archived projects reject writes")
    _, h, _ = api("GET", f"/projects/{A}")
    status, h, proj = api("PATCH", f"/projects/{A}", {"status": "archived"}, {"If-Match": h["ETag"]})
    check(status == 200 and proj["status"] == "archived", "project A archived")
    for method, path, body, extra in (
        ("POST", f"/projects/{A}/sources", src_body, {"Idempotency-Key": key()}),
        ("POST", f"/projects/{A}/uploads", {"filename": "a.csv", "mime_type": "text/csv", "size_bytes": 3,
                                            "kind": "dataset", "origin": "simulated"}, {"Idempotency-Key": key()}),
        ("POST", f"/projects/{A}/experiments", exp_body, {"Idempotency-Key": key()}),
        ("PATCH", epath, {"title": "While archived"}, {"If-Match": '"2"'}),
    ):
        status, _, err = api(method, path, body, extra)
        check(status == 409 and code(err) == "PROJECT_ARCHIVED", f"{method} {path.split('/')[-1] or path} on archived project returns 409")
    status, _, data = raw("GET", f"/projects/{A}/artifacts/{csv_art['id']}/content")
    check(status == 200 and data == csv, "archived project content remains readable")
    status, h, proj = api("PATCH", f"/projects/{A}", {"status": "active"}, {"If-Match": h["ETag"]})
    check(status == 200 and proj["status"] == "active", "project A restored")

    print("11. Lists and workspace counts")
    status, _, page = api("GET", f"/projects/{A}/artifacts?kind=dataset&limit=1")
    all_items, pages = list(page["items"]), 1
    while page["next_cursor"]:
        status, _, page = api("GET", f"/projects/{A}/artifacts?limit=1&cursor={page['next_cursor']}")
        all_items += page["items"]
        pages += 1
    check(all(i["kind"] == "dataset" for i in all_items) and csv_art["id"] in [i["id"] for i in all_items],
          "artifact cursor pagination preserves the kind filter")
    status, _, err = api("GET", f"/projects/{A}/artifacts?kind=bogus")
    check(status == 400 and code(err) == "INVALID_QUERY", "unknown kind filter returns 400")
    _, _, everything = api("GET", f"/projects/{A}/artifacts?limit=100")
    _, _, ws = api("GET", f"/projects/{A}/workspace")
    check(ws["counts"] == {"sources": 1, "experiments": 1, "runs": 0, "artifacts": len(everything["items"])}
          and len(everything["items"]) == 3, f"workspace counts reflect persisted resources ({ws['counts']})")

    print("12. Event delivery, ordering, and resume")
    wait_for(lambda: any(e["json"]["type"] == "project.updated" and e["json"]["payload"]["project"]["status"] == "active"
                         for e in s1.events), 10, "events through the restore")
    seqs = [sequence(e["id"]) for e in s1.events]
    check(seqs == sorted(seqs) and len(set(seqs)) == len(seqs) and seqs[0] == sequence(cursor0) + 1,
          "events arrive once each, in order, starting right after the workspace cursor")
    check(all(e["id"] == e["json"]["cursor"] and e["event"] == e["json"]["type"] and e["json"]["project_id"] == A
              for e in s1.events), "SSE id/event match the ProjectEvent and belong to project A only")
    types = {e["event"] for e in s1.events}
    check({"source.created", "upload.updated", "artifact.created", "experiment.updated", "project.updated"} <= types,
          f"stream includes resource events ({sorted(types)})")
    created = [e["json"]["payload"]["artifact"]["id"] for e in s1.events if e["event"] == "artifact.created"]
    check(created == [png_art["id"], vid["id"], csv_art["id"]], "artifact.created events match committed artifacts")
    check("retry" in s1.fields, "stream sends an SSE retry hint")
    middle = s1.events[len(s1.events) // 2]
    s2 = open_stream(f"/projects/{A}/events?after={cursor0}", {"Last-Event-ID": middle["id"]})
    wait_for(lambda: len(s2.events) >= 1, 10, "resumed events")
    check(s2.events[0]["id"] == s1.events[len(s1.events) // 2 + 1]["id"], "Last-Event-ID takes precedence over ?after=")
    s3 = open_stream(f"/projects/{A}/events?after={cursor0}")
    wait_for(lambda: len(s3.events) >= len(s1.events), 10, "replayed events")
    check([e["id"] for e in s3.events[:len(s1.events)]] == [e["id"] for e in s1.events], "replay from a cursor is identical")

    if args.skip_heartbeat:
        print("Heartbeat check skipped.")
    else:
        s4 = open_stream(f"/projects/{B}/events")
        wait_for(lambda: any("heartbeat" in c for c in s4.comments), 20, "idle heartbeat")
        check(not s4.events, "idle stream with no cursor starts live and sends a comment heartbeat within 15 s")

    print(f"\nPASS: {len(PASSED)} checks. Projects {A} and {B} were left in place.")


