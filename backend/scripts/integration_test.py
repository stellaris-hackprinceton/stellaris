BACKEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.environ.get("STELLARIS_API_URL", "http://127.0.0.1:8000/api/v1").rstrip("/")
_PARSED = urllib.parse.urlsplit(BASE)
PASSED = []


def check(condition, message):
    if not condition:
        raise AssertionError(message)
    PASSED.append(message)
    print(f"  ok  {message}")


def key():
    return f"it-{uuid.uuid4().hex}"


def raw(method, path, data=None, headers=None):
    req = urllib.request.Request(BASE + path, data=data, method=method, headers=dict(headers or {}))
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return resp.status, resp.headers, resp.read()
    except urllib.error.HTTPError as err:
        return err.code, err.headers, err.read()


def api(method, path, body=None, headers=None):
    hdrs = dict(headers or {})
    data = None
    if body is not None:
        data = json.dumps(body).encode()
        hdrs.setdefault("Content-Type", "application/json")
    status, resp_headers, payload = raw(method, path, data, hdrs)
    return status, resp_headers, json.loads(payload) if payload else None


def code(body):
    return (body or {}).get("error", {}).get("code")


def docker(*args, check_rc=True):
    result = subprocess.run(["docker", *args], capture_output=True, cwd=BACKEND_DIR)
    if check_rc and result.returncode != 0:
        raise RuntimeError(f"docker {' '.join(args)} failed: {result.stderr.decode(errors='replace').strip()}")
    return result


def container_for(project_id):
    out = docker("ps", "-a", "--filter", f"label=stellaris.project_id={project_id}",
                 "--filter", "label=stellaris.role=project-runtime", "--format", "{{.Names}}").stdout.split()
    return out[0].decode() if len(out) == 1 else None


# -- fixtures (all SIMULATED) -------------------------------------------------------

def make_png(width, height):
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    rows = b"".join(b"\x00" + bytes(v for x in range(width) for v in ((x * 8) % 256, (y * 10) % 256, 128))
                    for y in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b""))


def make_video():
    """1 s, 64x48, 10 fps synthetic test pattern generated by ffmpeg inside the api container."""
    path = f"/tmp/stellaris-it-{uuid.uuid4().hex}.mp4"
    docker("compose", "exec", "-T", "api", "ffmpeg", "-y", "-v", "error", "-f", "lavfi",
           "-i", "testsrc=size=64x48:rate=10", "-t", "1", "-c:v", "mpeg4", path)
    data = docker("compose", "exec", "-T", "api", "cat", path).stdout
    docker("compose", "exec", "-T", "api", "rm", "-f", path, check_rc=False)
    return data


# -- upload helpers -------------------------------------------------------------------

def create_upload(pid, data, filename, mime, kind, *, sha=True, extra=None):
    body = {"filename": filename, "mime_type": mime, "size_bytes": len(data), "kind": kind, "origin": "simulated",
            **({"sha256": hashlib.sha256(data).hexdigest()} if sha else {}), **(extra or {})}
    return api("POST", f"/projects/{pid}/uploads", body, {"Idempotency-Key": key()})


def put(pid, upload_id, data, mime, chunked=False):
    payload = (data[i:i + 4096] for i in range(0, len(data), 4096)) if chunked else data
    status, _, body = raw("PUT", f"/projects/{pid}/uploads/{upload_id}/content", payload, {"Content-Type": mime})
    return status, json.loads(body) if body else None


def complete(pid, upload_id, idem=None):
    return api("POST", f"/projects/{pid}/uploads/{upload_id}/complete", {}, {"Idempotency-Key": idem or key()})


def upload_artifact(pid, data, filename, mime, kind, chunked=False):
    status, _, up = create_upload(pid, data, filename, mime, kind)
    assert status == 201, up
    status, body = put(pid, up["id"], data, mime, chunked)
    assert status == 204, body
    status, _, art = complete(pid, up["id"])
    assert status == 200, art
    return up, art


# -- SSE ------------------------------------------------------------------------------

class Stream(threading.Thread):
    def __init__(self, path, headers=None):
        super().__init__(daemon=True)
        self.path, self.headers = path, headers or {}
        self.status = self.resp_headers = None
        self.events, self.comments, self.fields = [], [], []
        self.ready = threading.Event()

    def run(self):
        conn = http.client.HTTPConnection(_PARSED.hostname, _PARSED.port or 80, timeout=60)
        try:
            conn.request("GET", _PARSED.path + self.path, headers={"Accept": "text/event-stream", **self.headers})
            resp = conn.getresponse()
            self.status, self.resp_headers = resp.status, resp.headers
            self.ready.set()
            if resp.status != 200:
                return
            current = {}
            while True:
                line = resp.readline()
                if not line:
                    return
                text = line.decode().rstrip("\r\n")
                if text == "":
                    if "data" in current:
                        current["json"] = json.loads(current["data"])
                        self.events.append(current)
                    current = {}
                elif text.startswith(":"):
                    self.comments.append(text)
                else:
                    name, _, value = text.partition(":")
                    current[name] = value[1:] if value.startswith(" ") else value
                    self.fields.append(name)
        except (OSError, http.client.HTTPException):
            return
        finally:
            self.ready.set()
            conn.close()


def open_stream(path, headers=None):
    stream = Stream(path, headers)
    stream.start()
    stream.ready.wait(15)
    return stream


def wait_for(predicate, timeout, what):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(0.2)
    raise AssertionError(f"timed out waiting for {what}")


def sequence(cursor):
    return int(cursor.split("_")[1])  # Test-only peek at our own cursor format.


