"""Report runs: project-contained Deep Agent interpretation with a recorded evidence appendix.

Inputs come from the accepted report snapshot (evidence run IDs, selected source snapshots,
project research question) and from each terminal evidence run's own committed records:
its accepted input snapshot (method, calibration, hypothesis as they were when that run was
accepted), status/error, warnings, measurements with values and uncertainties, claims,
charts/annotated media, code, logs, and provenance links. Failed or cancelled evidence runs
are reported as such, including their missing measurements. A successfully generated
report says nothing about whether any experiment succeeded, and the report states that.
"""

import json
import re
from urllib.parse import quote, urlsplit

from .artifacts import commit_artifact
from .http import new_id, now_ts

GENERATOR = "stellaris_api.reports/report_deep_agent_v2"
LEGACY_GENERATOR = "stellaris_api.reports/report_markdown_v1"
MAX_MEASUREMENT_ROWS = 500


def _cell(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _inline(text: str) -> str:
    return re.sub(r"[\r\n]+", " ", str(text)).strip()


def _citation_text(value) -> str:
    """Render citation metadata as plain Markdown text, not active markup."""
    text = _inline("" if value is None else value)
    return re.sub(r"([\\`*_{}\[\]()#+.!|>~-])", r"\\\1", text)


def _source_link(source: dict) -> str:
    """Build a safe external Markdown link from a validated Source snapshot."""
    url = source.get("url", "")
    parts = urlsplit(url) if isinstance(url, str) else None
    if parts is None or parts.scheme not in ("http", "https") or not parts.netloc:
        return f"{_citation_text(source.get('title', 'Untitled source'))} (`{_citation_text(source.get('id', 'unknown'))}`)"
    # Parentheses and angle brackets can alter Markdown link destinations. Percent-encode
    # them while preserving URL delimiters and existing escapes.
    href = quote(url, safe=":/?#@!$&'*+,;=%")
    title = _citation_text(source.get("title", "Untitled source"))
    return f"[{title}]({href})"


def _num(value) -> str:
    if value is None:
        return "—"
    return f"{value:.6g}" if isinstance(value, float) else str(value)


def _quote(text: str) -> str:
    lines = (text or "").strip().splitlines() or ["(empty)"]
    return "\n".join("> " + line for line in lines)


class _Links:
    def __init__(self, project_id):
        self.base = f"/api/v1/projects/{project_id}"

    def content(self, artifact_id, inline=False):
        return f"{self.base}/artifacts/{artifact_id}/content" + ("?disposition=inline" if inline else "")

    def run(self, run_id):
        return f"{self.base}/runs/{run_id}"


def _load_evidence(conn, project_id, run_id):
    row = conn.execute("SELECT doc, snapshot, warnings FROM runs WHERE id = ? AND project_id = ?",
                       (run_id, project_id)).fetchone()
    run, snapshot = json.loads(row["doc"]), json.loads(row["snapshot"])
    measurements = [json.loads(r["doc"]) for r in conn.execute(
        "SELECT doc FROM measurements WHERE run_id = ? AND project_id = ? ORDER BY created_at, id", (run_id, project_id))]
    claims = [json.loads(r["doc"]) for r in conn.execute(
        "SELECT doc FROM claims WHERE run_id = ? AND project_id = ? ORDER BY created_at, id", (run_id, project_id))]
    artifacts = [json.loads(r["doc"]) for r in conn.execute(
        "SELECT doc FROM artifacts WHERE run_id = ? AND project_id = ? ORDER BY created_at, id", (run_id, project_id))]
    simulated = (snapshot.get("simulated") or any(m["data_origin"] == "simulated" for m in measurements)
                 or any(a["origin"] == "simulated" for a in artifacts))
    return {"run": run, "snapshot": snapshot, "warnings": json.loads(row["warnings"]), "measurements": measurements,
            "claims": claims, "artifacts": artifacts, "simulated": simulated}


def build_markdown(project_id, report_run_id, snapshot, evidence, provenance_id, generated_at, *, analysis_session=None):
    L = _Links(project_id)
    out = []
    w = out.append
    any_sim = any(e["simulated"] for e in evidence)
    w(f"# {_inline(snapshot['title'])}\n")
    label = "Agent-analyzed Markdown report" if analysis_session else "Deterministic Markdown report"
    w(f"*{label} generated by Stellaris report run [{report_run_id}]({L.run(report_run_id)}) "
      f"at {generated_at} from persisted evidence only. Generating this report does not mean any experiment "
      f"succeeded; each evidence run's own status is stated below.*\n")
    if any_sim:
        w("> **SIMULATED DATA.** At least one evidence run analysed simulated (synthetic) input. Every value from such "
          "a run is labelled *simulated* below and is not an observation of a physical experiment.\n")

    if analysis_session is not None:
        analysis = analysis_session.analysis
        w("## Scientific interpretation (AI)\n")
        w(f"**Hypothesis assessment: {analysis['assessment']}.**\n")
        w("This interpretation was produced by the configured LangChain Deep Agent. It is an inference from "
          "the referenced records, not a new observation or independent confirmation. Exact recorded evidence follows.\n")
        w(analysis["interpretation_markdown"].strip() + "\n")
        w("### Interpretation limitations\n")
        for item in analysis["limitations"]:
            w(f"- {_citation_text(item)}")
        w("\n### Supporting records\n")
        for ref in dict.fromkeys(analysis["references"]):
            if ref.startswith("run_"):
                href = L.run(ref)
            elif ref.startswith("src_"):
                href = f"{L.base}/sources/{ref}"
            elif ref.startswith("msr_"):
                run_id = next((e['run']['id'] for e in evidence if any(m['id'] == ref for m in e['measurements'])), None)
                href = f"{L.run(run_id)}/measurements" if run_id else L.content(provenance_id)
            elif ref.startswith("art_"):
                href = L.content(ref)
            elif ref.startswith("clm_"):
                href = f"{L.base}/claims/{ref}"
            else:
                href = f"{L.base}/experiments/{ref}"
            w(f"- [{ref}]({href})")
        if analysis_session.calculations:
            w("\n### Reproducible report calculations\n")
            for result in analysis_session.calculations:
                w(f"- Calculation [{result['run_id']}]({L.run(result['run_id'])}): {result['status']}. "
                  "See its saved code, inputs, outputs, and provenance for reproduction.")
        w("\n## Recorded scientific evidence\n")

    w("## Evidence runs\n")
    w("| Run | Pipeline | Status | Accepted | Finished | Valid / missing / rejected | Data |")
    w("| --- | --- | --- | --- | --- | --- | --- |")
    for e in evidence:
        run, ms = e["run"], e["measurements"]
        counts = "/".join(str(sum(m["status"] == s for m in ms)) for s in ("valid", "missing", "rejected"))
        status = run["status"] + (f" ({run['error']['code']})" if run["error"] else "")
        w(f"| [{run['id']}]({L.run(run['id'])}) | {_cell(run['input']['pipeline'])} | {_cell(status)} | "
          f"{_cell(e['snapshot']['accepted_at'])} | {_cell(run['finished_at'])} | {counts} | "
          f"{'**simulated**' if e['simulated'] else 'observed input'} |")
    w("")

    w("## Research question\n")
    rq = snapshot["project"].get("research_question")
    w(f"{_inline(rq)}\n" if rq else "_No research question was recorded for this project when the report was requested._\n")

    w("## Hypothesis\n")
    hypotheses = {}
    for e in evidence:
        exp = e["snapshot"]["experiment"]
        hypotheses.setdefault(exp["hypothesis"].strip() or "(empty)", []).append(
            f"{exp['id']} revision {exp['revision']} (run {e['run']['id']})")
    for text, where in hypotheses.items():
        w(_quote(text))
        w(f"\n*From the accepted experiment snapshot of: {', '.join(where)}. This is a proposed hypothesis, "
          "not a result.*\n")

    selected_sources = snapshot.get("sources", [])
    cited_sources = {}
    for e in evidence:
        accepted_sources = {s["id"]: s for s in e["snapshot"].get("sources", []) if isinstance(s, dict) and s.get("id")}
        for claim in e["claims"]:
            for citation in claim.get("citations", []):
                source_id = citation.get("source_id") if isinstance(citation, dict) else None
                source = accepted_sources.get(source_id)
                if source is not None:
                    cited_sources.setdefault(source_id, source)

    w("## Sources\n")
    if selected_sources:
        w("### Selected for this report\n")
        for s in selected_sources:
            authors = ", ".join(s["authors"]) if s["authors"] else "unknown authors"
            status = {"metadata_only": "metadata only — the document itself was not inspected",
                      "abstract_retrieved": "abstract retrieved — the full text was not inspected",
                      "full_text_retrieved": "full text retrieved", "failed": "retrieval failed"}[s["retrieval_status"]]
            extra = f", DOI {_citation_text(s['doi'])}" if s.get("doi") else ""
            w(f"- {_source_link(s)} — {_citation_text(authors)}"
              f"{', ' + _citation_text(s['published_at']) if s.get('published_at') else ''}{extra}. Source `{_citation_text(s['id'])}` "
              f"({s['provider']}; {status}).")
    cited_only = [source for source_id, source in cited_sources.items()
                  if source_id not in {s.get("id") for s in selected_sources}]
    if cited_only:
        w("\n### Cited by evidence claims\n")
        for s in cited_only:
            w(f"- {_source_link(s)} — source `{_citation_text(s['id'])}` ({s['provider']}; "
              f"{s['retrieval_status']}).")
    if not selected_sources and not cited_only:
        w("_No sources were selected for this report._\n")
    else:
        w("")

    for e in evidence:
        _run_section(w, L, e)

    w("## Uncertainty and limitations\n")
    w("- Reported uncertainties are the statistical estimates stated next to each value (method given). They exclude "
      "systematic effects such as perspective, lens distortion, motion blur, and segmentation bias unless stated.")
    w("- An uncertainty shown as *unknown* was not estimated; it does not mean zero error.")
    w("- Missing and rejected measurements are listed with their reasons; no value was interpolated or invented.")
    limitations = []
    for e in evidence:
        for item in e["snapshot"]["experiment"].get("limitations", []):
            if item not in limitations:
                limitations.append(item)
    for item in limitations:
        w(f"- Experiment limitation: {_inline(item)}")
    if any_sim:
        w("- Simulated inputs test the measurement pipeline; they are not evidence about a physical system.")
    w("")
    w("## Provenance\n")
    w(f"- This report's provenance manifest: [{provenance_id}]({L.content(provenance_id)})")
    if analysis_session is not None:
        w(f"- Report generator: `{GENERATOR}`. Model: `{_inline(analysis_session.metadata['model'])}` "
          f"via `{analysis_session.metadata['provider']}`.")
        w("- Model interpretation may vary between runs. The original evidence and calculation records remain immutable.")
    else:
        w(f"- Report generator: `{LEGACY_GENERATOR}` (deterministic; no language model was used).")
    w(f"- Report run: [{report_run_id}]({L.run(report_run_id)})")
    return "\n".join(out) + "\n"


def _run_section(w, L, e):
    run, snap = e["run"], e["snapshot"]
    exp = snap["experiment"]
    sim = " — SIMULATED INPUT" if e["simulated"] else ""
    w(f"## Evidence run {run['id']}{sim}\n")
    w(f"- **Status:** {run['status']}" + (f" — `{run['error']['code']}`: {_inline(run['error']['message'])}"
                                         if run["error"] else ""))
    if run["status"] != "succeeded":
        w("- **This run did not succeed.** Any values below are partial evidence committed before it ended.")
    w(f"- **Run:** [{run['id']}]({L.run(run['id'])}); accepted {snap['accepted_at']}, started "
      f"{run['started_at'] or '—'}, finished {run['finished_at'] or '—'}.")
    w(f"- **Pipeline:** `{snap['pipeline']['name']}` version {snap['pipeline']['version']}; parameters "
      f"`{json.dumps(snap['parameters'], sort_keys=True)}`.")
    code = next((a for a in e["artifacts"] if a["kind"] == "code"), None) or snap.get("code")
    if code:
        w(f"- **Executed code:** [{_cell(code['filename'])}]({L.content(code['id'])}) (sha256 `{code['sha256']}`).")
    if run["result_summary"]:
        w(f"- **Result summary:** {_inline(run['result_summary'])}")
    w("- **Inputs:**")
    for a in snap["inputs"]:
        meta = a["metadata"]
        dims = f", {meta['width_px']}×{meta['height_px']} px" if meta.get("width_px") else ""
        dur = f", {meta['duration_ms'] / 1000:.3f} s" if meta.get("duration_ms") else ""
        w(f"  - [`{a['id']}`]({L.content(a['id'])}) {_cell(a['filename'])} ({a['mime_type']}, origin "
          f"**{a['origin']}**{dims}{dur}, sha256 `{a['sha256']}`)")
    w("")

    w(f"### Method (accepted experiment snapshot {exp['id']} revision {exp['revision']})\n")
    w(f"**{_inline(exp['title'])}** — {exp['method']} experiment.\n")
    w(_quote(exp["protocol_markdown"]) + "\n")
    if exp["variables"]:
        w("Variables:")
        for v in exp["variables"]:
            w(f"- {_cell(v['name'])} ({v['role']}{', ' + v['unit'] if v['unit'] else ''}): {_inline(v['description'])}")
        w("")
    if exp["success_criteria"]:
        w("Success criteria (as planned; not evaluated automatically):")
        for c in exp["success_criteria"]:
            w(f"- {_inline(c)}")
        w("")

    w("### Calibration\n")
    cal, conv = exp["calibration"], snap.get("calibration_conversion")
    if cal["mode"] == "none" or not conv:
        w("No reference-length calibration: lengths are reported in pixels and no physical scale was assumed.")
    else:
        unc = conv["reference_uncertainty_m"]
        w(f"Reference length {conv['reference_length_m']} m"
          f"{f' ± {unc} m' if unc is not None else ' (uncertainty not stated)'} over {conv['pixel_distance']:.3f} px "
          f"in artifact `{conv['calibration_artifact_id']}` frame {conv['frame_index']} → "
          f"{conv['meters_per_pixel']:.6g} m/px.")
    for item in cal.get("assumptions", []) + snap.get("calibration_assumptions", []):
        w(f"- Assumption: {_inline(item)}")
    w("")

    ms = e["measurements"]
    w(f"### Measurements ({len(ms)})\n")
    if ms:
        w("| Series | Quantity | Value | Unit | Uncertainty | Time (s) | Status | Data origin | Evidence |")
        w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for m in ms[:MAX_MEASUREMENT_ROWS]:
            u = m["uncertainty"]
            unc = f"± {_num(u['absolute'])} ({u['method']})" if u["absolute"] is not None else "unknown"
            status = m["status"]
            if status != "valid":
                reason = next((a for a in reversed(m["assumptions"]) if a.startswith(("Not ",))), m["assumptions"][-1])
                status = f"{status}: {reason}"
            origin = "**simulated**" if m["data_origin"] == "simulated" else m["data_origin"]
            evidence = ", ".join(f"`{ev['artifact_id']}`" + (f" frame {ev['frame_index']}" if ev["frame_index"] is not None
                                                            else "") + (f" row {ev['row_index']}" if ev["row_index"]
                                                                        is not None else "") for ev in m["evidence"][:3])
            w(f"| {_cell(m['series'])} | {_cell(m['quantity'])} | {_num(m['value'])} | {_cell(m['unit'])} | "
              f"{_cell(unc)} | {_num(m['time_s'])} | {_cell(status)} | {origin} | {_cell(evidence)} |")
        if len(ms) > MAX_MEASUREMENT_ROWS:
            w(f"\n*{len(ms) - MAX_MEASUREMENT_ROWS} further measurements are omitted here; see "
              f"{L.run(run['id'])}/measurements.*")
        assumptions = []
        for m in ms:
            for a in m["assumptions"]:
                if a not in assumptions and not a.startswith("Not "):
                    assumptions.append(a)
        if assumptions:
            w("\nMeasurement assumptions:")
            for a in assumptions[:40]:
                w(f"- {_inline(a)}")
    else:
        w("_No measurements were committed for this run._")
    w("")

    if e["claims"]:
        w("### Claims\n")
        accepted_sources = {s["id"]: s for s in snap.get("sources", []) if isinstance(s, dict) and s.get("id")}
        for c in e["claims"]:
            label = {"observation": "Observation", "inference": "Inference", "hypothesis": "Hypothesis (proposed)"}[c["kind"]]
            w(f"- **{label}:** {_inline(c['text'])}")
            for citation in c.get("citations", []):
                if not isinstance(citation, dict):
                    continue
                source_id = citation.get("source_id")
                source = accepted_sources.get(source_id)
                if source is None:
                    w(f"  - Citation source `{_citation_text(source_id)}` is absent from this run's accepted source snapshot.")
                    continue
                details = []
                if citation.get("locator"):
                    details.append(f"locator: {_citation_text(citation['locator'])}")
                if citation.get("excerpt"):
                    details.append(f"excerpt: “{_citation_text(citation['excerpt'])}”")
                suffix = f" ({'; '.join(details)})" if details else ""
                w(f"  - Citation: {_source_link(source)}{suffix}")
            for a in c["assumptions"]:
                w(f"  - Assumption: {_inline(a)}")
            for lim in c["limitations"]:
                w(f"  - Limitation: {_inline(lim)}")
        w("")

    visuals = [a for a in e["artifacts"] if a["kind"] in ("chart", "image")]
    if visuals:
        w("### Plots and annotated media\n")
        for a in visuals:
            label = ("Chart" if a["kind"] == "chart" else "Annotated frame") + (" (simulated)" if a["origin"] == "simulated" else "")
            w(f"![{_cell(label)}: {_cell(a['filename'])}]({L.content(a['id'], inline=True)})\n")
    data = [a for a in e["artifacts"] if a["kind"] == "dataset"]
    if data:
        w("Data files: " + ", ".join(f"[{_cell(a['filename'])}]({L.content(a['id'])})" for a in data) + "\n")

    if e["warnings"] or run["error"]:
        w("### Warnings and failures\n")
        if run["error"]:
            w(f"- **{run['error']['code']}**: {_inline(run['error']['message'])}")
        for warning in e["warnings"]:
            w(f"- {warning['code']}: {_inline(warning['message'])}")
        w("")

    w("### Run provenance\n")
    if run["provenance_artifact_id"]:
        w(f"- Provenance manifest: [{run['provenance_artifact_id']}]({L.content(run['provenance_artifact_id'])})")
    else:
        w("- No provenance manifest was committed for this run.")
    logs = [a for a in e["artifacts"] if a["kind"] == "log"]
    for a in logs:
        w(f"- Log: [{_cell(a['filename'])}]({L.content(a['id'])})")
    w("")


def _filename(title: str) -> str:
    base = re.sub(r"[^A-Za-z0-9._ -]+", "", title).strip().replace(" ", "-")[:120].strip(".-") or "report"
    return f"{base}.md"


def handle_report(ctx):
    from .report_analysis import analyze_report
    snap = ctx.snapshot
    ctx.progress("collecting evidence", 0.1, "Reading committed evidence.", force=True)
    evidence = [_load_evidence(ctx.conn, ctx.project_id, item["id"]) for item in snap["evidence_runs"]]
    for e in evidence:
        run = e["run"]
        if run["status"] != "succeeded":
            ctx.warn("EVIDENCE_RUN_NOT_SUCCEEDED", f"Evidence run {run['id']} ended {run['status']}"
                     + (f" ({run['error']['code']})" if run["error"] else "") + "; its evidence is partial.")
        if not e["measurements"]:
            ctx.warn("NO_MEASUREMENTS", f"Evidence run {run['id']} committed no measurements.")
    if any(e["simulated"] for e in evidence):
        ctx.warn("SIMULATED_EVIDENCE", "The report includes results derived from simulated input.")
    if ctx.cancel_requested():
        ctx.finish("cancelled", summary="Cancelled.")
        return

    session = analyze_report(ctx, evidence)
    if session is None:  # Failed/cancelled analysis has already retained its audit records.
        return
    ctx.progress("writing report", None, "Saving agent interpretation and recorded evidence.", force=True)
    generated_at = now_ts()
    report_id, prov_id = new_id("art"), new_id("art")
    text = build_markdown(ctx.project_id, ctx.run_id, snap, evidence, prov_id, generated_at, analysis_session=session)
    parents = []
    for e in evidence:
        if e["run"]["provenance_artifact_id"]:
            parents.append(e["run"]["provenance_artifact_id"])
        parents += [a["id"] for a in e["artifacts"] if a["kind"] == "chart"]
    parents = list(dict.fromkeys(parents))[:200]
    report = ctx.stage_text(text, filename=_filename(snap["title"]), mime_type="text/markdown", kind="report",
                            origin="generated", parent_artifact_ids=parents, artifact_id=report_id)
    ctx.log.system(f"Report assembled ({len(text.encode('utf-8'))} bytes, sha256 {report['sha256']}).")
    provenance = {
        "schema": "stellaris.provenance.v1", "run_id": ctx.run_id, "project_id": ctx.project_id,
        "generated_at": generated_at,
        "accepted_snapshot": {"input": ctx.input, "accepted_at": snap["accepted_at"],
                              "evidence_runs": snap["evidence_runs"], "selected_sources": snap["sources"],
                              "research_question": snap["project"]["research_question"]},
        "generator": GENERATOR, "model_provider": session.metadata["provider"], "model": session.metadata["model"],
        "agent_analysis": {**session.metadata, "assessment": session.analysis["assessment"],
                           "references": session.analysis["references"], "limitations": session.analysis["limitations"],
                           "evidence_reads": session.reads, "calculations": session.calculations},
        "evidence_used": [{"run_id": e["run"]["id"], "status": e["run"]["status"], "revision": e["run"]["revision"],
                           "provenance_artifact_id": e["run"]["provenance_artifact_id"],
                           "measurement_ids": [m["id"] for m in e["measurements"]],
                           "claim_ids": [c["id"] for c in e["claims"]], "simulated": e["simulated"]} for e in evidence],
        "outputs": [{"artifact_id": report["id"], "filename": report["filename"], "sha256": report["sha256"],
                     "size_bytes": report["size_bytes"], "mime_type": report["mime_type"]}],
        "warnings": ctx.warnings,
        "reproducibility_limits": ["Model interpretation may vary between invocations. Exact evidence, context read hashes, "
                                   "model identity, and isolated calculation runs are retained.",
                                   "AI interpretation is not independent scientific verification."],
    }
    log_staged = ctx.stage_text(ctx.log.text(), filename="run-log.txt", mime_type="text/plain", kind="log",
                                origin="generated")
    prov = ctx.stage_text(json.dumps(provenance, indent=1, allow_nan=False), filename="provenance.json",
                          mime_type="application/json", kind="environment", origin="generated", artifact_id=prov_id)
    summary = f"Agent-analyzed Markdown report generated from {len(evidence)} evidence run(s). Hypothesis: {session.analysis['assessment']}."
    if any(e["run"]["status"] != "succeeded" for e in evidence):
        summary += " Some evidence runs did not succeed; the report describes them as partial evidence."
    if any(e["simulated"] for e in evidence):
        summary += " Includes SIMULATED results."

    def publish(conn):
        commit_artifact(conn, report)

    ctx.finish("succeeded", summary=summary, publish=publish, retained=[log_staged], provenance=prov)
